    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        Contact contact;
        int id;
        String fullName;
        String email;
        String cellPhoneNumber;
        String instagram;
        String Facebook;
        boolean isKnown;
        String type; // Family, HisgScool,Job...
        char gender;
        ArrayList<String> hobbies;
        Date birthDate;
        String comments;

        try {
            id = Integer.parseInt(txtId.getText().trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(rootPane, "Please enter a valid numeric id.");
            return;
        }

        fullName = txtFullName.getText();
        email = txtEmail.getText();
        cellPhoneNumber = txtCellphoneNumber.getText();
        instagram = txtInstagram.getText();
        Facebook = txtFacebook.getText();
        isKnown = chkIsKnown.isSelected();
        type = (String) cmbTypeOfContact.getSelectedItem();
        gender = cmbGender.getSelectedItem().toString().charAt(0);
        hobbies = new ArrayList<>(lstHobbies.getSelectedValuesList());
        birthDate = new Date();
        comments = txaComments.getText();

        contact = new Contact(id, fullName, email, cellPhoneNumber, instagram, Facebook, isKnown, type, gender, hobbies, birthDate, comments);

        JOptionPane.showMessageDialog(rootPane, contact);
    }//GEN-LAST:event_btnSaveActionPerformed

