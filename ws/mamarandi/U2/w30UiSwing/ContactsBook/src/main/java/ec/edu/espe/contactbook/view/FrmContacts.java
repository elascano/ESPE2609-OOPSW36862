    private void btmSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btmSaveActionPerformed
         Contact contact;
    int id;
    String fullName;
    String email;
    String cellPhoneNumber;
    String instagram;
    String facebook;
    boolean isKnown;
    String type;
    char gender;
    ArrayList<String> hobbies;
    Date birthDate;
    String comments;

    id = Integer.parseInt(txtid.getText());
    fullName = jTextField1.getText();
    email = jTextField2.getText();
    cellPhoneNumber = jTextField3.getText();
    instagram = jTextField4.getText();
    facebook = jTextField5.getText();
    isKnown = chkIsKnown.isSelected();
    type = (String) cmbTypeOfContact.getSelectedItem();
    gender = cmbGender.getSelectedItem().toString().charAt(0);
    hobbies = new ArrayList<>(lstModels.getSelectedValuesList());
    birthDate = new Date();
    comments = jTextArea1.getText();

    contact = new Contact(
        id, fullName, email, cellPhoneNumber,
        instagram, facebook, isKnown, type,
        gender, hobbies, birthDate, comments
    );

    JOptionPane.showMessageDialog(rootPane, contact);
        
        

    }//GEN-LAST:event_btmSaveActionPerformed

