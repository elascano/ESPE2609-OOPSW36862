    private void setupInputRestrictions() {
        // Only allow digits in ID and Cell Phone Number
        java.awt.event.KeyAdapter numbersOnly = new java.awt.event.KeyAdapter() {
            @Override
            public void keyTyped(java.awt.event.KeyEvent evt) {
                char c = evt.getKeyChar();
                if (!Character.isDigit(c) && c != java.awt.event.KeyEvent.VK_BACK_SPACE) {
                    evt.consume();
                }
            }
        };
        txtId.addKeyListener(numbersOnly);
        txtCellPhoneNumber.addKeyListener(numbersOnly);

        // Only allow letters and spaces in Full Name
        txtFullName.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyTyped(java.awt.event.KeyEvent evt) {
                char c = evt.getKeyChar();
                if (!Character.isLetter(c) && !Character.isWhitespace(c) && c != java.awt.event.KeyEvent.VK_BACK_SPACE) {
                    evt.consume();
                }
            }
        });
    }

